-- Notifications use the fields already consumed by the frontend data layer.
create or replace function public.notify_aquawell_order_progress()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_title text;
  v_message text;
begin
  if new.status is distinct from old.status then
    v_title := 'Order update';
    v_message := case new.status
      when 'CONFIRMED' then 'Your order has been confirmed by station staff.'
      when 'OUT FOR-DELIVERY' then 'Your order is out for delivery.'
      when 'DELIVERED' then 'Your rider marked the order as delivered. Please confirm receipt in My Orders.'
      when 'READY FOR PICKUP' then 'Your order is ready for station pickup.'
      when 'PICKED UP' then 'Your pickup order has been completed.'
      when 'CANCELLED' then 'Your order was cancelled.'
      else 'Your order status has changed to ' || new.status || '.'
    end;
    if new.customer_id is not null then
      insert into public.notifications(user_id, title, description, order_id, unread, created_at)
      values (new.customer_id, v_title, v_message, new.id, true, now());
    end if;
  end if;
  if new.customer_received_at is distinct from old.customer_received_at and new.customer_received_at is not null then
    insert into public.notifications(user_id, title, description, order_id, unread, created_at)
    select p.id, 'Delivery receipt confirmed', 'The customer confirmed receipt of a delivered order.', new.id, true, now()
    from public.profiles p where p.role in ('admin','staff');
  end if;
  if new.rider_id is distinct from old.rider_id and new.rider_id is not null then
    insert into public.notifications(user_id, title, description, order_id, unread, created_at)
    values (new.rider_id, 'Delivery assigned', 'A delivery has been assigned to you.', new.id, true, now());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_notify_aquawell_order_progress on public.orders;
create trigger trg_notify_aquawell_order_progress
after update of status, rider_id, customer_received_at on public.orders
for each row execute function public.notify_aquawell_order_progress();

