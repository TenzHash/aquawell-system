create or replace function public.set_aquawell_order_reference()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if new.order_reference is null or btrim(new.order_reference) = '' then
    if new.id is not null then
      new.order_reference := 'AW-' || lpad(new.id::text, 7, '0');
    else
      new.order_reference := 'AW-' || lpad(nextval('public.aquawell_order_reference_seq')::text, 7, '0');
    end if;
  end if;
  return new;
end;
$$;

