-- Restrict direct customer receipt updates to a dedicated RPC; do not grant broad order UPDATE access here.
-- Existing order RLS and server-side policies must be audited before applying the RPC below.
create or replace function public.confirm_customer_order_receipt(p_order_id bigint)
returns public.orders
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_order public.orders;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  update public.orders o
     set customer_received_at = now()
   where o.id = p_order_id
     and o.customer_id = auth.uid()
     and o.type = 'Delivery'
     and o.status = 'DELIVERED'
     and o.customer_received_at is null
  returning o.* into v_order;
  if not found then raise exception 'Receipt confirmation is only available for your delivered orders'; end if;
  return v_order;
end;
$$;
revoke all on function public.confirm_customer_order_receipt(bigint) from public;
grant execute on function public.confirm_customer_order_receipt(bigint) to authenticated;



-- Server-enforced delivery state transition. Rider can only update an order assigned to them.
create or replace function public.update_assigned_delivery_status(p_order_id bigint, p_status text)
returns public.orders
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_order public.orders;
  v_role text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_status not in ('OUT FOR-DELIVERY', 'DELIVERED') then raise exception 'Unsupported delivery status'; end if;
  select p.role into v_role from public.profiles p where p.id = auth.uid();
  if v_role not in ('delivery','staff','admin') then raise exception 'Not permitted to update delivery status'; end if;
  update public.orders o
     set status = p_status
   where o.id = p_order_id
     and o.type = 'Delivery'
     and (v_role in ('staff','admin') or o.rider_id = auth.uid())
     and ((p_status = 'OUT FOR-DELIVERY' and o.status in ('CONFIRMED','OUT FOR-DELIVERY'))
       or (p_status = 'DELIVERED' and o.status = 'OUT FOR-DELIVERY'))
  returning o.* into v_order;
  if not found then raise exception 'Order is not assigned to this rider or transition is not allowed'; end if;
  return v_order;
end;
$$;
revoke all on function public.update_assigned_delivery_status(bigint,text) from public;
grant execute on function public.update_assigned_delivery_status(bigint,text) to authenticated;



create or replace function public.assign_delivery_rider(p_order_id bigint, p_rider_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_order public.orders;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','staff')) then
    raise exception 'Only staff or admin can assign delivery riders';
  end if;
  if not exists (select 1 from public.profiles p where p.id = p_rider_id and p.role = 'delivery' and p.delivery_availability = 'AVAILABLE') then
    raise exception 'Rider is unavailable or does not have a delivery role';
  end if;
  if exists (select 1 from public.orders o where o.rider_id = p_rider_id and o.type = 'Delivery' and o.status = 'OUT FOR-DELIVERY') then
    raise exception 'Rider already has an active out-for-delivery assignment';
  end if;
  update public.orders o set rider_id = p_rider_id
   where o.id = p_order_id and o.type = 'Delivery' and o.status = 'CONFIRMED'
  returning o.* into v_order;
  if not found then raise exception 'Only confirmed delivery orders can be assigned'; end if;
  return v_order;
end;
$$;
revoke all on function public.assign_delivery_rider(bigint,uuid) from public;
grant execute on function public.assign_delivery_rider(bigint,uuid) to authenticated;

create or replace function public.reject_delivery_assignment(p_order_id bigint)
returns public.orders
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_order public.orders;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'delivery') then
    raise exception 'Only delivery riders can reject an assignment';
  end if;
  update public.orders o set rider_id = null
   where o.id = p_order_id and o.rider_id = auth.uid() and o.type = 'Delivery' and o.status = 'CONFIRMED'
  returning o.* into v_order;
  if not found then raise exception 'Only your assigned, not-yet-dispatched delivery can be rejected'; end if;
  return v_order;
end;
$$;
revoke all on function public.reject_delivery_assignment(bigint) from public;
grant execute on function public.reject_delivery_assignment(bigint) to authenticated;

create or replace function public.set_delivery_availability(p_availability text)
returns public.profiles
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_profile public.profiles;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_availability not in ('AVAILABLE','UNAVAILABLE') then raise exception 'Invalid availability'; end if;
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'delivery') then
    raise exception 'Only delivery riders can change availability';
  end if;
  if p_availability = 'UNAVAILABLE' and exists (
    select 1 from public.orders o where o.rider_id = auth.uid() and o.type = 'Delivery' and o.status = 'OUT FOR-DELIVERY'
  ) then raise exception 'Finish active out-for-delivery work before marking unavailable'; end if;
  update public.profiles set delivery_availability = p_availability where id = auth.uid() returning * into v_profile;
  return v_profile;
end;
$$;
revoke all on function public.set_delivery_availability(text) from public;
grant execute on function public.set_delivery_availability(text) to authenticated;

