-- Everything is additive and idempotent (safe to run twice).

begin;

-- ---------------------------------------------------------------- 1. schema tweaks
-- Inventory categories: gallons, caps and seals in addition to the original two.
alter table public.inventory drop constraint if exists inventory_category_check;
alter table public.inventory add constraint inventory_category_check
  check (category in ('Refill','Hardware','Round Gallon','Slim Gallon','Caps','Seals'));

alter table public.orders add column if not exists dest_lat double precision;
alter table public.orders add column if not exists dest_lng double precision;
alter table public.orders add column if not exists out_for_delivery_at timestamptz;
alter table public.orders add column if not exists walk_in_customer_name text;

-- Performance: indexes on every foreign key / filter column used by the app.
create index if not exists order_items_inventory_idx   on public.order_items(inventory_id);
create index if not exists payments_order_status_idx   on public.payments(order_id, payment_status);
create index if not exists orders_completed_at_idx     on public.orders(completed_at desc) where completed_at is not null;
create index if not exists orders_payment_status_idx   on public.orders(payment_status) where payment_status in ('PENDING','UNPAID');
create index if not exists notifications_unread_idx    on public.notifications(user_id) where unread;
create index if not exists sales_order_idx             on public.sales(order_id);

-- ---------------------------------------------------------------- 2. permissions (RBAC)
create table if not exists public.role_permissions (
  role       text not null check (role in ('staff','delivery')),
  permission text not null,
  enabled    boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id) on delete set null,
  primary key (role, permission)
);
alter table public.role_permissions enable row level security;
drop policy if exists role_permissions_read on public.role_permissions;
create policy role_permissions_read on public.role_permissions for select to authenticated using (true);

insert into public.role_permissions(role, permission, enabled) values
  ('staff','view_orders',true),('staff','confirm_orders',true),('staff','cancel_orders',true),('staff','walk_in_sales',true),
  ('staff','view_inventory',true),('staff','adjust_inventory',true),('staff','manage_inventory',false),
  ('staff','collect_payments',true),('staff','issue_receipts',true),('staff','view_customers',true),
  ('staff','view_companies',true),('staff','view_live_map',true),
  ('delivery','collect_payments',false),('delivery','issue_receipts',true),('delivery','view_live_map',true),('delivery','view_customer_contact',true)
on conflict (role, permission) do nothing;

create or replace function public.has_permission(p_permission text)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare r text := public.current_role(); v boolean;
begin
  if r = 'admin' then return true; end if;
  if r not in ('staff','delivery') then return false; end if;
  select enabled into v from public.role_permissions where role = r and permission = p_permission;
  return coalesce(v, false);
end $$;

create or replace function public.admin_set_permission(p_role text, p_permission text, p_enabled boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if public.current_role() <> 'admin' then raise exception 'Only the administrator can change permissions.'; end if;
  if p_role not in ('staff','delivery') then raise exception 'Unsupported role.'; end if;
  insert into public.role_permissions(role, permission, enabled, updated_by) values (p_role, p_permission, p_enabled, auth.uid())
  on conflict (role, permission) do update set enabled = excluded.enabled, updated_at = now(), updated_by = auth.uid();
  perform public.write_audit(format('%s "%s" for %s', case when p_enabled then 'Allowed' else 'Blocked' end, p_permission, p_role), 'ACCESS');
end $$;

-- ---------------------------------------------------------------- 3. stock ledger + low-stock alerts
create table if not exists public.inventory_movements (
  id           bigint generated by default as identity primary key,
  inventory_id bigint not null references public.inventory(id) on delete cascade,
  item_name    text not null,
  delta        integer not null,
  stock_before integer not null,
  stock_after  integer not null check (stock_after >= 0),
  reason       text not null default 'Stock change',
  actor_id     uuid references public.profiles(id) on delete set null,
  actor_name   text,
  created_at   timestamptz not null default now()
);
create index if not exists inventory_movements_item_idx on public.inventory_movements(inventory_id, created_at desc);
create index if not exists inventory_movements_created_idx on public.inventory_movements(created_at desc);
alter table public.inventory_movements enable row level security;
drop policy if exists inventory_movements_read on public.inventory_movements;
create policy inventory_movements_read on public.inventory_movements for select to authenticated
  using (public.current_role() in ('admin','staff'));

-- Every stock change is logged in the same transaction as the change itself, and crossing the
-- low-stock level notifies admins and staff once.
create or replace function public.log_inventory_change()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_reason text := coalesce(nullif(current_setting('aquawell.reason', true), ''), 'Stock change'); v_name text;
begin
  if tg_op = 'INSERT' then
    if new.stock > 0 then
      insert into public.inventory_movements(inventory_id,item_name,delta,stock_before,stock_after,reason,actor_id,actor_name)
      values (new.id,new.name,new.stock,0,new.stock,'Opening stock',auth.uid(),(select full_name from public.profiles where id=auth.uid()));
    end if;
    return new;
  end if;
  if new.stock is distinct from old.stock then
    select full_name into v_name from public.profiles where id = auth.uid();
    insert into public.inventory_movements(inventory_id,item_name,delta,stock_before,stock_after,reason,actor_id,actor_name)
    values (new.id,new.name,new.stock-old.stock,old.stock,new.stock,v_reason,auth.uid(),v_name);
    if old.stock > old.min_stock and new.stock <= new.min_stock then
      insert into public.notifications(user_id,title,description)
      select p.id,'Low stock alert', format('%s is down to %s (alert level %s). Please restock soon.', new.name, new.stock, new.min_stock)
      from public.profiles p where p.role in ('admin','staff');
    end if;
  end if;
  return new;
end $$;
drop trigger if exists inventory_change_log on public.inventory;
create trigger inventory_change_log after insert or update of stock on public.inventory
  for each row execute function public.log_inventory_change();

-- ---------------------------------------------------------------- 4. inventory create / update / delete
create or replace function public.create_inventory_item(p_name text, p_category text, p_price numeric, p_stock integer, p_min_stock integer)
returns public.inventory language plpgsql security definer set search_path = public as $$
declare r public.inventory;
begin
  if not public.has_permission('manage_inventory') then raise exception 'not allowed: manage_inventory'; end if;
  perform set_config('aquawell.reason','Opening stock',true);
  insert into public.inventory(name,category,price,stock,min_stock) values (btrim(p_name),p_category,p_price,p_stock,p_min_stock) returning * into r;
  perform public.write_audit('Added inventory item '||r.name,'INVENTORY');
  return r;
end $$;

create or replace function public.update_inventory_item(p_id bigint, p_name text, p_category text, p_price numeric, p_stock integer, p_min_stock integer)
returns public.inventory language plpgsql security definer set search_path = public as $$
declare r public.inventory;
begin
  if not public.has_permission('manage_inventory') then raise exception 'not allowed: manage_inventory'; end if;
  perform set_config('aquawell.reason','Manual stock correction',true);
  update public.inventory set name=btrim(p_name),category=p_category,price=p_price,stock=p_stock,min_stock=p_min_stock,updated_at=now()
   where id=p_id returning * into r;
  if not found then raise exception 'Item not found.'; end if;
  perform public.write_audit('Updated inventory item '||r.name,'INVENTORY');
  return r;
end $$;

create or replace function public.delete_inventory_item(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_name text;
begin
  if not public.has_permission('manage_inventory') then raise exception 'not allowed: manage_inventory'; end if;
  select name into v_name from public.inventory where id=p_id;
  if v_name is null then raise exception 'Item not found.'; end if;
  if exists (select 1 from public.order_items where inventory_id=p_id) then
    raise exception 'This item has order history and cannot be deleted.';
  end if;
  delete from public.inventory where id=p_id;      -- movements cascade
  perform public.write_audit('Deleted inventory item '||v_name,'INVENTORY');
end $$;

-- Stock adjustments now respect the permission switch and record a reason.
create or replace function public.adjust_inventory_stock(p_inventory_id bigint, p_delta integer)
returns public.inventory language plpgsql security definer set search_path = public as $$
declare r public.inventory;
begin
  if not public.has_permission('adjust_inventory') then raise exception 'not allowed: adjust_inventory'; end if;
  if p_delta is null or p_delta = 0 then raise exception 'Enter a stock change other than zero.'; end if;
  perform set_config('aquawell.reason', case when p_delta>0 then 'Stock received' else 'Stock removed' end, true);
  update public.inventory set stock = stock + p_delta, updated_at = now() where id = p_inventory_id returning * into r;
  if not found then raise exception 'Item not found.'; end if;
  perform public.write_audit(format('Adjusted stock of %s by %s', r.name, p_delta),'INVENTORY');
  return r;
end $$;

-- ---------------------------------------------------------------- 5. per-order payment
create or replace function public.mark_order_paid(p_order_id bigint)
returns public.orders language plpgsql security definer set search_path = public as $$
declare o public.orders; pay public.payments; v_role text := public.current_role(); v_name text; v_items text; v_qty integer;
begin
  select * into o from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  if not public.has_permission('collect_payments') then raise exception 'not allowed: collect_payments'; end if;
  if v_role = 'delivery' and (o.rider_id is distinct from auth.uid() or o.status not in ('OUT FOR-DELIVERY','DELIVERED')) then
    raise exception 'not allowed: this delivery is not assigned to you';
  end if;
  if o.status in ('PENDING','CANCELLED') then raise exception 'This order must be confirmed before payment can be collected.'; end if;
  if o.payment_status = 'PAID' then raise exception 'This order is already paid.'; end if;
  select * into pay from public.payments where order_id = p_order_id and payment_status in ('PENDING','UNPAID') for update;
  if not found then raise exception 'No open payment was found for this order.'; end if;

  update public.payments set payment_status='PAID', paid_at=now(), verified_by=auth.uid(),
         payment_method = case when o.type='Delivery' then 'Cash on Delivery' else 'Cash' end, updated_at=now()
   where payment_id = pay.payment_id;
  update public.orders set payment_status='PAID', updated_at=now() where id = p_order_id returning * into o;

  select coalesce((select full_name from public.profiles where id=o.customer_id), o.walk_in_customer_name, 'Walk-in customer') into v_name;
  select string_agg(i.name||' × '||oi.quantity, ', '), sum(oi.quantity) into v_items, v_qty
    from public.order_items oi join public.inventory i on i.id=oi.inventory_id where oi.order_id=p_order_id;
  insert into public.sales(order_id,customer_name,item_name,quantity,total_amount,payment_method)
  values (p_order_id, v_name, coalesce(v_items,'Order'), greatest(coalesce(v_qty,1),1), o.total, case when o.type='Delivery' then 'Cash on Delivery' else 'Cash' end)
  on conflict (order_id) do nothing;

  if o.customer_id is not null then
    insert into public.notifications(user_id,title,description,order_id)
    values (o.customer_id,'Payment received',format('Payment for %s was received. Thank you!', o.order_reference),o.id);
  end if;
  perform public.write_audit('Collected payment for '||o.order_reference,'PAYMENT');
  return o;
end $$;

-- ---------------------------------------------------------------- 6. rider locations
create table if not exists public.rider_locations (
  rider_id   uuid primary key references public.profiles(id) on delete cascade,
  lat        double precision not null check (lat between -90 and 90),
  lng        double precision not null check (lng between -180 and 180),
  updated_at timestamptz not null default now()
);
alter table public.rider_locations enable row level security;
drop policy if exists rider_locations_read on public.rider_locations;
create policy rider_locations_read on public.rider_locations for select to authenticated using (
  rider_id = auth.uid() or public.current_role() in ('admin','staff')
  or exists (select 1 from public.orders o where o.rider_id = rider_locations.rider_id and o.customer_id = auth.uid()
             and o.status = 'OUT FOR-DELIVERY'));

create or replace function public.update_rider_location(p_lat double precision, p_lng double precision)
returns void language plpgsql security definer set search_path = public as $$
begin
  if public.current_role() <> 'delivery' then raise exception 'not allowed: riders only'; end if;
  insert into public.rider_locations(rider_id,lat,lng,updated_at) values (auth.uid(),p_lat,p_lng,now())
  on conflict (rider_id) do update set lat=excluded.lat, lng=excluded.lng, updated_at=now();
end $$;

-- ---------------------------------------------------------------- 7. privacy: export + deletion
create or replace function public.export_my_data()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'exported_at', now(),
    'profile', (select to_jsonb(p) - 'id' - 'role' - 'updated_at' from public.profiles p where p.id = auth.uid()),
    'orders', coalesce((select jsonb_agg(jsonb_build_object('reference',o.order_reference,'date',o.created_at,'type',o.type,'status',o.status,
        'payment_status',o.payment_status,'total',o.total,
        'items',(select coalesce(jsonb_agg(jsonb_build_object('name',i.name,'quantity',oi.quantity,'unit_price',oi.unit_price)),'[]'::jsonb)
                 from public.order_items oi join public.inventory i on i.id=oi.inventory_id where oi.order_id=o.id))
        order by o.created_at desc) from public.orders o where o.customer_id = auth.uid()),'[]'::jsonb),
    'notifications', coalesce((select jsonb_agg(jsonb_build_object('title',n.title,'description',n.description,'created_at',n.created_at))
        from public.notifications n where n.user_id = auth.uid()),'[]'::jsonb));
$$;

-- Permanently deletes the signed-in customer. Orders, payments and sales are kept for accounting but are
-- disconnected from the person (orders.customer_id has ON DELETE SET NULL); notifications, company links
-- and the profile are removed by cascade, then the sign-in record itself is deleted.
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = public, auth as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'You must be signed in.'; end if;
  if public.current_role() <> 'customer' then raise exception 'Only customer accounts can be deleted here.'; end if;
  if exists (select 1 from public.orders where customer_id = v_uid and status not in ('DELIVERED','PICKED UP','CANCELLED')) then
    raise exception 'You still have an active order.';
  end if;
  update public.sales s set customer_name = 'Deleted customer' where s.order_id in (select id from public.orders where customer_id = v_uid);
  update public.orders set walk_in_customer_name = 'Deleted customer', address = null where customer_id = v_uid;
  perform public.write_audit('A customer deleted their account','ACCOUNT', null);
  delete from public.profiles where id = v_uid;     -- cascades notifications + affiliations; orders.customer_id -> NULL
  delete from auth.users where id = v_uid;
end $$;

