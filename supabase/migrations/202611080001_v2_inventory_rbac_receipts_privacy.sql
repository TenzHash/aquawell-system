  public.create_inventory_item(text,text,numeric,integer,integer), public.update_inventory_item(bigint,text,text,numeric,integer,integer),
  public.delete_inventory_item(bigint), public.mark_order_paid(bigint), public.update_rider_location(double precision,double precision),
  public.export_my_data(), public.delete_my_account() to authenticated;

