-- Customer checkout is one transaction; prices/totals are read from inventory server-side.
create or replace function public.place_customer_order(p_type text,p_address text,p_items jsonb,p_payment_method text default null)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders; v_line jsonb; v_item public.inventory; v_qty integer; v_total numeric(12,2):=0; v_method text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if public.current_role() <> 'customer' then raise exception 'Only customer accounts can place customer orders'; end if;
  if p_type not in ('Delivery','Pickup') then raise exception 'Invalid fulfillment type'; end if;
  if p_type='Delivery' and coalesce(btrim(p_address),'')='' then raise exception 'Delivery address is required'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'At least one item is required'; end if;
  v_method := coalesce(p_payment_method, case when p_type='Pickup' then 'Cash' else 'Cash on Delivery' end);
  if p_type='Pickup' and v_method <> 'Cash' then raise exception 'Station Pickup payment method must be Cash'; end if;
  if v_method not in ('Cash','Cash on Delivery','GCash','Bank Transfer') then raise exception 'Invalid payment method'; end if;
  insert into public.orders(customer_id,type,address,total,status,payment_status) values(auth.uid(),p_type,nullif(btrim(p_address),''),0,'PENDING','PENDING') returning * into v_order;
  for v_line in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_line->>'quantity')::integer;
    if v_qty < 1 then raise exception 'Quantity must be a positive whole number'; end if;
    select * into v_item from public.inventory where id=(v_line->>'inventory_id')::bigint for share;
    if not found then raise exception 'An inventory item is unavailable'; end if;
    if v_item.stock < v_qty then raise exception 'Insufficient stock for %',v_item.name; end if;
    insert into public.order_items(order_id,inventory_id,quantity,unit_price) values(v_order.id,v_item.id,v_qty,v_item.price);
    v_total := v_total + v_item.price*v_qty;
  end loop;
  update public.orders set total=v_total where id=v_order.id returning * into v_order;
  insert into public.payments(order_id,amount,payment_method,payment_status) values(v_order.id,v_total,v_method,'PENDING');
  insert into public.notifications(user_id,title,description,order_id) values(auth.uid(),'Order submitted','Your order has been submitted successfully and is awaiting staff confirmation. Submission does not mean it has been accepted or prepared yet.',v_order.id);
  perform public.write_audit('Placed order '||v_order.order_reference,'ORDER',auth.uid());
  return v_order;
end; $$;

-- Atomic all-or-nothing stock deduction and order confirmation.
create or replace function public.confirm_order_and_deduct_stock(p_order_id bigint)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders; v_item record;
begin
  if auth.uid() is null or public.current_role() not in ('admin','staff') then raise exception 'Staff/admin access required'; end if;
  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if v_order.status='CONFIRMED' and v_order.stock_deducted then return v_order; end if;
  if v_order.status<>'PENDING' or v_order.stock_deducted then raise exception 'Only pending, not-yet-deducted orders can be confirmed'; end if;
  for v_item in select oi.inventory_id,oi.quantity,i.stock,i.name from public.order_items oi join public.inventory i on i.id=oi.inventory_id where oi.order_id=p_order_id order by oi.inventory_id for update of i loop
    if v_item.stock < v_item.quantity then raise exception 'Insufficient stock for %',v_item.name; end if;
  end loop;
  update public.inventory i set stock=i.stock-oi.quantity from public.order_items oi where oi.order_id=p_order_id and oi.inventory_id=i.id;
  update public.orders set status='CONFIRMED',stock_deducted=true where id=p_order_id returning * into v_order;
  if v_order.customer_id is not null then insert into public.notifications(user_id,title,description,order_id) values(v_order.customer_id,'Order confirmed','Station staff confirmed your order. It is now being processed.',v_order.id); end if;
  perform public.write_audit('Confirmed order '||v_order.order_reference,'ORDER');
  return v_order;
end; $$;

create or replace function public.assign_delivery_rider(p_order_id bigint,p_rider_id uuid)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders;
begin
 if auth.uid() is null or public.current_role() not in ('admin','staff') then raise exception 'Staff/admin access required'; end if;
 if not exists(select 1 from public.profiles where id=p_rider_id and role='delivery' and delivery_availability='AVAILABLE') then raise exception 'Rider is unavailable or invalid'; end if;
 if exists(select 1 from public.orders where rider_id=p_rider_id and type='Delivery' and status='OUT FOR-DELIVERY') then raise exception 'Rider already has an active delivery'; end if;
 update public.orders set rider_id=p_rider_id where id=p_order_id and type='Delivery' and status='CONFIRMED' and rider_id is null returning * into v_order;
 if not found then raise exception 'Only confirmed, unassigned delivery orders can be assigned'; end if;
 insert into public.delivery_events(order_id,actor_id,event_type) values(p_order_id,auth.uid(),'ASSIGNED');
 insert into public.notifications(user_id,title,description,order_id) values(p_rider_id,'Delivery assigned','A delivery has been assigned to you.',p_order_id);
 if v_order.customer_id is not null then insert into public.notifications(user_id,title,description,order_id) values(v_order.customer_id,'Rider assigned','A rider has been assigned to your order.',p_order_id); end if;
 perform public.write_audit('Assigned rider to order '||v_order.order_reference,'DELIVERY'); return v_order;
end; $$;

create or replace function public.reject_delivery_assignment(p_order_id bigint)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders;
begin
