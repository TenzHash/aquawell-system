 if not found then raise exception 'Only your pre-dispatch assignment can be rejected'; end if;
 insert into public.delivery_events(order_id,actor_id,event_type,details) values(p_order_id,auth.uid(),'REJECTED','Rider rejected assignment; order returned to unassigned queue');
 perform public.write_audit('Rejected delivery assignment for order '||v_order.order_reference,'DELIVERY'); return v_order;
end; $$;

create or replace function public.update_assigned_delivery_status(p_order_id bigint,p_status text)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders; v_event text;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 if p_status not in ('OUT FOR-DELIVERY','DELIVERED') then raise exception 'Unsupported delivery status'; end if;
 update public.orders set status=p_status where id=p_order_id and type='Delivery' and rider_id=auth.uid() and public.current_role()='delivery' and ((p_status='OUT FOR-DELIVERY' and status='CONFIRMED') or (p_status='DELIVERED' and status='OUT FOR-DELIVERY')) returning * into v_order;
 if not found then raise exception 'Order is not assigned to you or transition is not allowed'; end if;
 v_event := case when p_status='OUT FOR-DELIVERY' then 'OUT_FOR_DELIVERY' else 'RIDER_MARKED_DELIVERED' end;
 insert into public.delivery_events(order_id,actor_id,event_type) values(p_order_id,auth.uid(),v_event);
 if v_order.customer_id is not null then insert into public.notifications(user_id,title,description,order_id) values(v_order.customer_id,'Order update',case when p_status='OUT FOR-DELIVERY' then 'Your order is out for delivery.' else 'Your rider marked the order as delivered. Please confirm receipt.' end,p_order_id); end if;
 perform public.write_audit('Delivery status changed to '||p_status||' for order '||v_order.order_reference,'DELIVERY'); return v_order;
end; $$;

