create or replace function public.cancel_order_and_restore_stock(p_order_id bigint)
returns public.orders language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order public.orders;
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found then raise exception 'Order not found'; end if;
 if not (public.current_role() in ('admin','staff') or (public.current_role()='customer' and v_order.customer_id=auth.uid())) then raise exception 'Not permitted'; end if;
 if v_order.status not in ('PENDING','CONFIRMED') then raise exception 'This order can no longer be cancelled'; end if;
 if v_order.stock_deducted then
   update public.inventory i set stock=i.stock+oi.quantity from public.order_items oi where oi.order_id=p_order_id and oi.inventory_id=i.id;
 end if;
 update public.orders set status='CANCELLED',stock_deducted=false,cancellation_reason=coalesce(cancellation_reason,'Cancelled by authorized user') where id=p_order_id returning * into v_order;
 update public.payments set payment_status='CANCELLED',updated_at=now() where order_id=p_order_id and payment_status in ('PENDING','UNPAID');
 if v_order.customer_id is not null then insert into public.notifications(user_id,title,description,order_id) values(v_order.customer_id,'Order cancelled','Your order has been cancelled.',p_order_id); end if;
 perform public.write_audit('Cancelled order '||v_order.order_reference,'ORDER'); return v_order;
end; $$;

