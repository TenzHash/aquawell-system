-- Payment verification: receipt upload is evidence only; only this RPC marks PAID.
create or replace function public.verify_payment(p_payment_id bigint,p_payment_method text default null)
returns public.payments language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_payment public.payments; v_order public.orders;
begin
 if auth.uid() is null or public.current_role() not in ('admin','staff') then raise exception 'Staff/admin access required'; end if;
 select * into v_payment from public.payments where payment_id=p_payment_id for update;
 if not found then raise exception 'Payment not found'; end if;
 if v_payment.payment_status='CANCELLED' then raise exception 'Cancelled payment cannot be verified'; end if;
 update public.payments set payment_status='PAID',payment_method=coalesce(p_payment_method,payment_method),paid_at=now(),verified_by=auth.uid(),updated_at=now() where payment_id=p_payment_id returning * into v_payment;
 update public.orders set payment_status='PAID',updated_at=now() where id=v_payment.order_id returning * into v_order;
 insert into public.sales(order_id,customer_name,item_name,quantity,total_amount,payment_method,date,created_at)
 select v_order.id,coalesce(nullif(p.full_name,''),'Walk-in Customer'),coalesce(string_agg(i.name||' × '||oi.quantity,', ' order by i.name),'Order items'),coalesce(sum(oi.quantity),0),v_order.total,v_payment.payment_method,coalesce(v_payment.paid_at::date,current_date),coalesce(v_payment.paid_at,now())
 from public.order_items oi join public.inventory i on i.id=oi.inventory_id left join public.profiles p on p.id=v_order.customer_id where oi.order_id=v_order.id group by p.full_name
 on conflict(order_id) do update set customer_name=excluded.customer_name,item_name=excluded.item_name,quantity=excluded.quantity,total_amount=excluded.total_amount,payment_method=excluded.payment_method,date=excluded.date,created_at=excluded.created_at;
 if v_order.customer_id is not null then insert into public.notifications(user_id,title,description,order_id) values(v_order.customer_id,'Payment verified','Your payment has been verified.',v_order.id); end if;
 perform public.write_audit('Verified payment for order '||v_order.order_reference,'PAYMENT'); return v_payment;
end; $$;

create or replace function public.get_daily_wma_forecast()
returns table(inventory_id bigint,item_name text,current_stock integer,daily_average numeric,forecast_quantity numeric)
language sql stable security definer set search_path = pg_catalog, public as $$
 with daily as (
   select oi.inventory_id, o.created_at::date as day, sum(oi.quantity)::numeric as qty
   from public.order_items oi join public.orders o on o.id=oi.order_id join public.payments p on p.order_id=o.id and p.payment_status='PAID'
   where o.status <> 'CANCELLED' and o.created_at >= current_date-interval '30 days'
   group by oi.inventory_id,o.created_at::date
 ), recent as (
   select i.id as inventory_id,i.name,i.stock,
     coalesce(sum(case when d.day=current_date then d.qty end),0) as q0,
     coalesce(sum(case when d.day=current_date-1 then d.qty end),0) as q1,
     coalesce(sum(case when d.day=current_date-2 then d.qty end),0) as q2
   from public.inventory i left join daily d on d.inventory_id=i.id group by i.id,i.name,i.stock
 )
 select r.inventory_id,r.name,r.stock,round((r.q0+r.q1+r.q2)/3,2),round((r.q0*3+r.q1*2+r.q2*1)/6,2) from recent r
 where public.current_role()='admin';
$$;

create or replace function public.notify_order_status_change()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_message text;
begin
 if new.status is distinct from old.status and new.customer_id is not null then
   v_message := case new.status when 'CONFIRMED' then 'Station staff confirmed your order.' when 'OUT FOR-DELIVERY' then 'Your order is out for delivery.' when 'DELIVERED' then 'Your rider marked the order as delivered. Please confirm receipt.' when 'READY FOR PICKUP' then 'Your order is ready for station pickup.' when 'PICKED UP' then 'Your pickup order is completed.' when 'CANCELLED' then 'Your order was cancelled.' else 'Your order status changed to '||new.status||'.' end;
   insert into public.notifications(user_id,title,description,order_id) values(new.customer_id,'Order update',v_message,new.id);
 end if;
 return new;
end; $$;
create trigger orders_notify_status after update of status on public.orders for each row execute function public.notify_order_status_change();

